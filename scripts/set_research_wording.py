#!/usr/bin/env python3
"""Bring the fixed report wording of finished reports in line with the
current generator (html_report.py), so reports read as a research firm's
assessment rather than tool output:

  footer            "Generated by Coherent Quadrant · open this file after a terminal run"
                    -> "Coherent Quadrant · Independent market assessment based on desk research and primary research"
  chart subtitle    "(20 on chart · 120 in table · ~equal per quadrant · country-diverse)"
                    -> "(20 companies on the chart · 120 companies assessed)"
  definitions note  "(generated for this market — not a fixed template)." -> "(defined specifically for this market)."
  parameters note   "... are defined for <market> and used to calculate company scores below."
                    -> "The X and Y axes ... were defined for <market> and form the basis of the company scores below."

The JSON loses its empty "criteria.crawl" block (nothing reads it). Company
evidence is never touched. Run set_methodology.py afterwards for the
methodology panel.

    .\\.venv\\Scripts\\python.exe scripts\\set_research_wording.py ^
        --folder "C:\\Users\\me\\Desktop\\Fire Market Quadrant" [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

_EVIDENCE_CELL = re.compile(r'<td><div class="cq-ta-score-line">.*?</td>', re.S)
_RULES = [
    (re.compile(r'<p class="footer">Generated by Coherent Quadrant[^<]*</p>'),
     '<p class="footer">Coherent Quadrant · Independent market assessment based on desk research '
     'and primary research</p>'),
    (re.compile(r"\((\d+) on chart · (\d+) in table · ~equal per quadrant · country-diverse\)"),
     r"(\1 companies on the chart · \2 companies assessed)"),
    (re.compile(r"\(generated for this market — not a fixed template\)\."),
     "(defined specifically for this market)."),
    (re.compile(r"X and Y axes and these 10 parameters are defined for(\s*<strong>.*?</strong>\s*)"
                r"and used to calculate company scores below\.", re.S),
     r"The X and Y axes and these 10 parameters were defined for\1and form the basis of the "
     r"company scores below."),
]


def reword(html: str) -> str:
    cells: list[str] = []

    def stash(m: re.Match) -> str:
        cells.append(m.group(0))
        return f"\x00{len(cells) - 1}\x00"

    body = _EVIDENCE_CELL.sub(stash, html)
    for rx, repl in _RULES:
        body = rx.sub(repl, body)
    return re.sub(r"\x00(\d+)\x00", lambda m: cells[int(m.group(1))], body)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--folder", action="append", required=True)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    for folder in args.folder:
        for jp in sorted(Path(folder).glob("*_quadrant.json")):
            hp = jp.with_name(jp.name.replace("_quadrant.json", "_report.html"))
            html = hp.read_text(encoding="utf-8")
            new_html = reword(html)
            payload = json.loads(jp.read_text(encoding="utf-8"))
            crit = payload.get("criteria") or {}
            json_changed = "crawl" in crit and not crit["crawl"]
            if json_changed:
                del crit["crawl"]
            print(f"html {'changed' if new_html != html else 'same':7} "
                  f"json {'changed' if json_changed else 'same':7} {hp.name}")
            if not args.dry_run:
                if new_html != html:
                    hp.write_text(new_html, encoding="utf-8")
                if json_changed:
                    jp.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
